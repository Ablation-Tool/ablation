"""
hdl_html_extractor.py: HDL Designer HTML export parser.

HDL Designer exports VHDL/Verilog source as a frameset of HTML files:

  <stem>.htm                — frameset (JS navigation, no source text)
  <stem>ContentFrame0.htm   — VHDL/Verilog source in a <pre> block
  <stem>ContentFrame1.htm   — diagram canvas ("Side Data was not exported")
  <stem>ToolbarFrame*.htm   — navigation toolbar (no source text)

Source code is syntax-colored with <span> tags:
  class=K  — VHDL/Verilog keyword
  class=C  — comment
  class=T  — type name
  class=S  — string literal

Extraction strips the tags and HTML entities, leaving clean source text
identical to what the original .vhd or .v files contained.

The primary output path is to_semantic(), which returns a VerilogSemantic
built in-memory from all extracted source files in the directory — no disk
writes required.

Usage:
    ext = HdlHtmlExtractor.from_directory('/path/to/htmlexport/lcb/downlink/')
    print(ext.source_files())             # ['lcb_decoder.vhd', ...]
    print(ext.text('lcb_decoder.vhd'))    # clean VHDL
    vs = ext.to_semantic()
    print(vs.constants())                 # all named constants

Known targets:
  /media/cowboy/research/CERN/sims/lcb/downlink/   — LCB downlink (10 files)
  /media/cowboy/research/CERN/sims/star_flink/readout130/  — STAR FLINK (5 files)
  /media/cowboy/research/CERN/docs/htmlexport/atlys/       — Atlys ITSDAQ (17 files)
  /media/cowboy/research/CERN/docs/htmlexport/hsio/        — HSIO (29 files)
  /media/cowboy/research/CERN/docs/htmlexport/ocb/         — OCB (10 files)
  /media/cowboy/research/CERN/docs/htmlexport/readout130/  — readout130 (7 files)
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from ablation.analyzers.verilog_semantic import (
    VerilogSemantic,
    _SourceEntry,
    _extract_vhdl,
    _extract_verilog,
)


# ── HTML entity table ─────────────────────────────────────────────────────────

_HTML_ENTITIES: List[Tuple[str, str]] = [
    ("&amp;",  "&"),
    ("&lt;",   "<"),
    ("&gt;",   ">"),
    ("&nbsp;", " "),
    ("&quot;", '"'),
    ("&#39;",  "'"),
]

# Span tags and all other HTML tags
_TAG_RE = re.compile(r"<[^>]+>", re.DOTALL)

# Sentinel text emitted by HDL Designer when the diagram has no side data
_NO_SIDE_DATA = "Side Data was not exported"

# Generator comment in every HDL Designer HTML file
_HDL_DESIGNER_RE = re.compile(r"Generated by HDL Designer", re.IGNORECASE)


# ── Internal helpers ──────────────────────────────────────────────────────────

def _strip_html(raw: str) -> str:
    """Remove all HTML tags and unescape entities."""
    text = _TAG_RE.sub("", raw)
    for entity, char in _HTML_ENTITIES:
        text = text.replace(entity, char)
    return text


def _extract_pre(raw: str) -> Optional[str]:
    """
    Return the content of the first <pre>...</pre> block, stripped of tags.
    Returns None if no <pre> block found or the block is a no-content frame.
    """
    pre_start = raw.find("<pre>")
    if pre_start == -1:
        pre_start = raw.lower().find("<pre>")
    if pre_start == -1:
        return None
    pre_end = raw.find("</pre>", pre_start)
    if pre_end == -1:
        # Truncated file — take everything after <pre>
        block = raw[pre_start + 5:]
    else:
        block = raw[pre_start + 5:pre_end]
    text = _strip_html(block)
    if _NO_SIDE_DATA in text:
        return None
    return text


def _source_name_from_stem(stem: str) -> str:
    """
    Map HDL Designer stem name to a canonical source filename.

    HDL Designer encodes the source extension in the stem:
      lcb_decoder_vhd   → lcb_decoder.vhd
      star_flink_v       → star_flink.v
      some_mod_vhdl      → some_mod.vhdl
    """
    for suffix, ext in (("_vhdl", ".vhdl"), ("_vhd", ".vhd"), ("_v", ".v")):
        if stem.endswith(suffix):
            return stem[: -len(suffix)] + ext
    # Fallback: use stem as-is
    return stem


# ── Public API ────────────────────────────────────────────────────────────────

@dataclass
class HdlHtmlExtractor:
    """
    Extracts VHDL/Verilog source text from HDL Designer HTML exports.

    Build with HdlHtmlExtractor.from_directory(path).
    """

    _src_dir: str
    # source filename (e.g. 'lcb_decoder.vhd') -> clean text
    _texts: Dict[str, str] = field(default_factory=dict)

    # ── Construction ──────────────────────────────────────────────────────────

    @classmethod
    def from_directory(cls, src_dir: str) -> "HdlHtmlExtractor":
        """
        Scan *src_dir* for HDL Designer ContentFrame0.htm files and extract
        clean source text from each.

        All subdirectories are searched recursively so that a top-level
        htmlexport directory (with atlys/, hsio/, etc. sub-dirs) works too.
        """
        root = Path(src_dir)
        texts: Dict[str, str] = {}

        for htm_path in sorted(root.rglob("*ContentFrame0.htm")):
            try:
                raw = htm_path.read_text(encoding="iso-8859-1", errors="replace")
            except OSError:
                continue

            # Validate: must be an HDL Designer export
            if not _HDL_DESIGNER_RE.search(raw):
                continue

            text = _extract_pre(raw)
            if text is None:
                continue  # diagram-only frame or no code

            # Derive the canonical source filename from the .htm stem
            # e.g. lcb_decoder_vhdContentFrame0.htm → stem = lcb_decoder_vhd
            stem = htm_path.stem.replace("ContentFrame0", "")
            source_name = _source_name_from_stem(stem)
            texts[source_name] = text

        obj = cls(_src_dir=str(src_dir))
        obj._texts = texts
        return obj

    # ── Accessors ─────────────────────────────────────────────────────────────

    def source_files(self) -> List[str]:
        """Sorted list of source filenames extracted from the HTML export."""
        return sorted(self._texts.keys())

    def text(self, source_name: str) -> str:
        """Clean source text for *source_name*. KeyError if not found."""
        return self._texts[source_name]

    def texts(self) -> Dict[str, str]:
        """All extracted texts as {source_name: clean_text}."""
        return dict(self._texts)

    def __len__(self) -> int:
        return len(self._texts)

    def __bool__(self) -> bool:
        return bool(self._texts)

    # ── VerilogSemantic bridge ─────────────────────────────────────────────────

    def to_semantic(self) -> VerilogSemantic:
        """
        Build a VerilogSemantic from all extracted source files.

        No disk writes — the clean text is processed in-memory using the
        same _extract_vhdl/_extract_verilog functions that from_directory() uses.
        The src_dir label is set to the original HTML export directory.
        """
        entries: List[_SourceEntry] = []
        lines_index = []
        module_ranges: Dict[str, List[Tuple[str, int]]] = {}

        for source_name, text in sorted(self._texts.items()):
            fname = source_name  # logical filename for annotation
            for lineno, line in enumerate(text.splitlines(), 1):
                lines_index.append((fname, lineno, line))
            if source_name.endswith(".v"):
                _extract_verilog(text, fname, entries, module_ranges)
            else:
                _extract_vhdl(text, fname, entries)

        vs = VerilogSemantic(entries, self._src_dir)
        vs._lines = lines_index  # type: ignore[attr-defined]
        vs._module_ranges = module_ranges  # type: ignore[attr-defined]
        return vs

    # ── Disk output ───────────────────────────────────────────────────────────

    def write_vhd(self, output_dir: str) -> List[str]:
        """
        Write clean source files to *output_dir*.

        Useful for feeding into HDLVersionDiff.from_directories() or tools
        that require files on disk. Returns list of written paths.
        """
        out = Path(output_dir)
        out.mkdir(parents=True, exist_ok=True)
        written = []
        for source_name, text in sorted(self._texts.items()):
            dest = out / source_name
            dest.write_text(text, encoding="utf-8")
            written.append(str(dest))
        return written

    # ── Reporting ─────────────────────────────────────────────────────────────

    def report(self) -> str:
        """One-block summary of what was extracted."""
        lines = [
            f"HdlHtmlExtractor: {self._src_dir}",
            f"  source files found : {len(self._texts)}",
        ]
        for name in self.source_files():
            text = self._texts[name]
            nlines = text.count("\n")
            lines.append(f"    {name:<40} {nlines:>5} lines")
        return "\n".join(lines)
