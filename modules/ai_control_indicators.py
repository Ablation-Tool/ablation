"""
ai_control_indicators.py: AI-generated code pattern detector.

Detects strings and comment patterns characteristic of AI code generation tools.
Code produced by GitHub Copilot, ChatGPT, Claude, and similar tools has elevated
vulnerability rates (Cornell/NYU research: ~40% higher than human-written code
for security-relevant patterns). Presence of AI generation markers flags a binary
for elevated review priority.

Detected indicators:
  - Copilot generation comment headers: /* Generated by GitHub Copilot */
  - ChatGPT/GPT-4 attribution strings (some tools auto-add these)
  - Characteristic AI-generated comment templates: "This function ... "
  - AI coding assistant completion markers used by certain IDEs
  - Claude / Anthropic generation markers
  - Tabnine, Amazon CodeWhisperer, Codeium markers
  - AI-hallucinated package name patterns (seen in generated import stubs)

Usage:
    detector = AIControlIndicators('/path/to/binary')
    findings = detector.scan()
    print(detector.report(findings))
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import List, Optional


# Direct AI tool attribution strings
_AI_GENERATION_STRINGS: list[bytes] = [
    b'Generated by GitHub Copilot',
    b'GitHub Copilot suggestion',
    b'Copilot generated',
    b'Generated by ChatGPT',
    b'Generated by GPT-4',
    b'Generated by Claude',
    b'Generated by Amazon CodeWhisperer',
    b'Generated by Tabnine',
    b'Generated by Codeium',
    b'AI-generated code',
    b'This code was generated by an AI',
    b'Auto-generated by Copilot',
]

# AI-hallucinated package names that appear in import stubs
_HALLUCINATED_PKGS: list[bytes] = [
    b'langchain-tools',
    b'openai-functions',
    b'anthropic-sdk-extra',
    b'gpt-utils',
    b'copilot-helper',
    b'chatgpt-client',
    b'ai-helper-utils',
    b'openai-helper',
    b'langchain-community-extra',
]

# Patterns characteristic of AI-generated comment style
_AI_COMMENT_PATS: list[re.Pattern] = [
    re.compile(rb'//\s*This function (?:takes|accepts|returns|handles|checks|validates)', re.I),
    re.compile(rb'//\s*TODO:\s*(?:Add|Implement|Handle|Fix|Update)\s+(?:error|check|validation)', re.I),
    re.compile(rb'//\s*Note:\s*This (?:is|was) generated', re.I),
    re.compile(rb'/\*\s*\n\s*\*\s*@(?:param|return|throws)\b', re.I),  # boilerplate javadoc
]


@dataclass
class AICodeFinding:
    indicator_type:  str       # 'attribution_string', 'hallucinated_package', 'comment_pattern'
    matched:         str       # what was matched
    severity:        str       # MEDIUM for all (informational)

    def fmt(self) -> str:
        return (f"  {self.severity:6s}  [AI_CODE]  {self.indicator_type}\n"
                f"         {self.matched[:80]}")


class AIControlIndicators:
    """Detect AI-generated code markers in binary strings."""

    def __init__(self, path: str) -> None:
        self._path = path

    @classmethod
    def from_context(cls, ctx) -> 'AIControlIndicators':
        obj = cls.__new__(cls)
        obj._path = ctx.path
        return obj

    def _read_raw(self) -> bytes:
        try:
            return open(self._path, 'rb').read()
        except OSError:
            return b''

    def scan(self) -> List[AICodeFinding]:
        raw = self._read_raw()
        if not raw:
            return []

        findings: list[AICodeFinding] = []
        seen: set[str] = set()

        # Check 1: direct attribution strings
        for indicator in _AI_GENERATION_STRINGS:
            if indicator in raw:
                text = indicator.decode('ascii', errors='replace')
                key = f'attr:{text[:40]}'
                if key not in seen:
                    seen.add(key)
                    findings.append(AICodeFinding('attribution_string', text, 'MEDIUM'))

        # Check 2: hallucinated package names
        for pkg in _HALLUCINATED_PKGS:
            if pkg in raw:
                text = pkg.decode('ascii', errors='replace')
                key = f'pkg:{text}'
                if key not in seen:
                    seen.add(key)
                    findings.append(AICodeFinding('hallucinated_package', text, 'MEDIUM'))

        # Check 3: AI comment patterns
        for pat in _AI_COMMENT_PATS:
            m = pat.search(raw)
            if m:
                text = m.group(0).decode('ascii', errors='replace').strip()[:60]
                key = f'comment:{text[:30]}'
                if key not in seen:
                    seen.add(key)
                    findings.append(AICodeFinding('comment_pattern', text, 'MEDIUM'))

        return findings

    def report(self, findings: Optional[List[AICodeFinding]] = None) -> str:
        if findings is None:
            findings = self.scan()
        if not findings:
            return f'AIControlIndicators: no AI code markers in {self._path}'
        lines = [f'AIControlIndicators: {len(findings)} indicator(s) in {self._path}', '']
        for f in findings:
            lines.append(f.fmt())
            lines.append('')
        return '\n'.join(lines)
