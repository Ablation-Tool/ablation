"""Unit tests for Wave 3 static analyzers (RXVM, BEAM, AI-agent auditors)."""

from __future__ import annotations

import struct
from pathlib import Path

from ablation.analyzers import (
    AgentAuthorityAudit,
    AgentObservabilityAudit,
    AgentToolSurfaceEnumerator,
    AIControlIndicators,
    BeamObfuscationAnalyzer,
    RxvmCryptoAnalyzer,
    analyze_beam_bytes,
    analyze_rxvm_source,
    decode_rxvm_float16,
    hybrid_xxh1_fmix32_hash,
    murmur3_rxvm,
    rc4_crypt,
)


def _make_beam_iff(chunks: list[tuple[bytes, bytes]]) -> bytes:
    body = bytearray(b"BEAM")
    for tag, payload in chunks:
        assert len(tag) == 4
        body.extend(tag)
        body.extend(struct.pack(">I", len(payload)))
        body.extend(payload)
        pad = (-len(payload)) % 4
        if pad:
            body.extend(b"\x00" * pad)
    return b"FOR1" + struct.pack(">I", len(body)) + bytes(body)


def test_rxvm_crypto_primitives_and_source_analysis() -> None:
    ct = rc4_crypt(b"secret-key", b"ablation-rxvm")
    assert ct != b"ablation-rxvm"
    assert rc4_crypt(b"secret-key", ct) == b"ablation-rxvm"
    assert isinstance(hybrid_xxh1_fmix32_hash("hello"), int)
    assert isinstance(murmur3_rxvm("hello"), int)
    assert decode_rxvm_float16(0x00, 0x3C) == 1.0

    sample = "const uint32_t k = 0x85ebca6b; // rc4_ksa and murmur3 mix\n"
    report = analyze_rxvm_source(sample, source_name="sample.c")
    assert report.source == "sample.c"
    assert isinstance(RxvmCryptoAnalyzer().analyze_text(sample).findings, list)


def test_beam_obfuscation_analyzer_parses_synthetic_iff() -> None:
    raw = _make_beam_iff([
        (b"AtU8", struct.pack(">I", 0)),
        (b"Code", b"\x00" * 24),
        (b"StrT", b"hello_beam"),
    ])
    report = analyze_beam_bytes(raw, source_name="synthetic.beam")
    assert report.source == "synthetic.beam"
    assert report.valid_beam_header is True
    assert isinstance(report.findings, list)
    assert isinstance(BeamObfuscationAnalyzer().analyze_bytes(raw).findings, list)


def test_agent_and_ai_auditors_scan_synthetic_binary(tmp_path: Path) -> None:
    sample = tmp_path / "agent_sample.bin"
    payload = (
        b"\x00api.openai.com\x00"
        b'{"name":"bash","description":"Execute shell command","parameters":{"type":"object"}}\x00'
        b"/* Generated by GitHub Copilot */\x00"
        b"system\x00execve\x00"
    )
    sample.write_bytes(payload)

    auth = AgentAuthorityAudit(str(sample))
    auth_findings = auth.scan()
    assert isinstance(auth_findings, list)
    assert isinstance(auth.report(auth_findings), str)

    obs = AgentObservabilityAudit(str(sample))
    obs_findings = obs.scan()
    assert isinstance(obs_findings, list)
    assert isinstance(obs.report(obs_findings), str)

    tools = AgentToolSurfaceEnumerator(str(sample))
    tool_findings = tools.scan()
    assert any(f.tool_name == "bash" for f in tool_findings)
    assert "bash" in tools.report(tool_findings)

    ai_ctrl = AIControlIndicators(str(sample))
    ai_findings = ai_ctrl.scan()
    assert len(ai_findings) >= 1
    assert isinstance(ai_ctrl.report(ai_findings), str)
