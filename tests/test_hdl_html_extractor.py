# ── to_semantic() bridge ──────────────────────────────────────────────────────

def test_to_semantic_extracts_constants():
    """to_semantic().constants() must find VHDL constants in the extracted source."""
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "pkg_test_vhd", _FRAME0_VHDL)
        ext = HdlHtmlExtractor.from_directory(tmp)
        vs = ext.to_semantic()
        consts = vs.constants()
        assert "CLK_FREQ" in consts
        assert consts["CLK_FREQ"]["value"] == "40"
        assert "DATA_WIDTH" in consts
        assert consts["DATA_WIDTH"]["value"] == "8"


def test_to_semantic_extracts_verilog_params():
    """to_semantic().constants() must find Verilog parameters."""
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "my_mod_v", _FRAME0_VERILOG)
        ext = HdlHtmlExtractor.from_directory(tmp)
        vs = ext.to_semantic()
        consts = vs.constants()
        assert "COUNT_MAX" in consts
        assert consts["COUNT_MAX"]["value"] == "255"


def test_to_semantic_port_widths():
    """to_semantic().port_widths() must find signal widths."""
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "uut_vhd", _FRAME0_ENTITIES)
        ext = HdlHtmlExtractor.from_directory(tmp)
        vs = ext.to_semantic()
        pw = vs.port_widths()
        assert "data_in" in pw
        assert pw["data_in"] == 8
        assert pw["data_out"] == 8


def test_to_semantic_multi_file():
    """to_semantic() with multiple files should aggregate all constants."""
    pkg_body = """\
<body><pre>
<span class=K>constant</span> A : <span class=T>integer</span> := 1;
</pre></body></html>
"""
    rtl_body = """\
<body><pre>
<span class=K>constant</span> B : <span class=T>integer</span> := 2;
</pre></body></html>
"""
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "pkg_vhd", pkg_body)
        _make_export(tmp, "rtl_vhd", rtl_body)
        ext = HdlHtmlExtractor.from_directory(tmp)
        vs = ext.to_semantic()
        consts = vs.constants()
        assert "A" in consts
        assert "B" in consts


# ── write_vhd() ───────────────────────────────────────────────────────────────

