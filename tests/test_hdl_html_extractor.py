"""
Tests for HdlHtmlExtractor — HDL Designer HTML export parser.

Tests use synthetic minimal HTML that reproduces the exact structure
emitted by HDL Designer:
  - <pre> block with <span class=K/C/T/S> syntax coloring
  - ContentFrame0.htm (source code)
  - ContentFrame1.htm ("Side Data was not exported" — diagram canvas)
  - Top-level frameset .htm (JS navigation, no source)

All synthetic files include the "Generated by HDL Designer" marker
so they pass the validator check.
"""

import os
import tempfile
import pytest

from ablation.analyzers.hdl_html_extractor import HdlHtmlExtractor


# ── Synthetic HTML fragments ───────────────────────────────────────────────────

_HDL_HEADER = """\
<!DOCTYPE html PUBLIC "-//W3C//DTD HTML 4.0 Transitional//EN">
<html><head>
<title>test_vhd</title>
<!-- Generated by HDL Designer -->
<!--    at 12:00:00 on 01/01/24 -->
</head>
"""

_FRAME0_VHDL = """\
<body><pre>
<span class=K>package</span> pkg_test <span class=K>is</span>
  <span class=K>constant</span> CLK_FREQ : <span class=T>integer</span> := 40;
  <span class=K>constant</span> DATA_WIDTH : <span class=T>integer</span> := 8;
  <span class=K>signal</span> my_flag : <span class=T>std_logic</span>;
<span class=K>end</span> pkg_test;
</pre></body></html>
"""

_FRAME1_SIDE_DATA = """\
<body>
Side Data was not exported
</body></html>
"""

_FRAMESET = """\
<html><head>
<title>test_vhd</title>
<!-- Generated by HDL Designer -->
</head>
<body></body></html>
"""

_FRAME0_VERILOG = """\
<body><pre>
<span class=K>module</span> my_mod (clk, rst);
  <span class=K>parameter</span> COUNT_MAX = 255;
  `<span class=K>define</span> TICK_NS 25
<span class=K>endmodule</span>
</pre></body></html>
"""

_FRAME0_ENTITIES = """\
<body><pre>
<span class=C>-- A comment with &amp; entities &lt; &gt;</span>
<span class=K>architecture</span> rtl <span class=K>of</span> uut <span class=K>is</span>
  <span class=K>signal</span> data_in  : <span class=T>std_logic_vector</span>(7 <span class=K>downto</span> 0);
  <span class=K>signal</span> data_out : <span class=T>std_logic_vector</span>(7 <span class=K>downto</span> 0);
<span class=K>begin</span>
<span class=K>end</span> rtl;
</pre></body></html>
"""


def _make_export(tmp_dir: str, stem: str, frame0_body: str,
                 frame1_body: str = _FRAME1_SIDE_DATA,
                 frameset_body: str = _FRAMESET) -> None:
    """Write a minimal HDL Designer HTML export set for one source file."""
    for suffix, content in (
        ("ContentFrame0.htm", _HDL_HEADER + frame0_body),
        ("ContentFrame1.htm", _HDL_HEADER + frame1_body),
        (".htm",              frameset_body),
    ):
        with open(os.path.join(tmp_dir, stem + suffix), "w") as f:
            f.write(content)


# ── from_directory tests ───────────────────────────────────────────────────────

def test_finds_content_frame0_files():
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "test_vhd", _FRAME0_VHDL)
        ext = HdlHtmlExtractor.from_directory(tmp)
        assert "test.vhd" in ext.source_files()


def test_source_file_count():
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "mod_a_vhd", _FRAME0_VHDL)
        _make_export(tmp, "mod_b_vhd", _FRAME0_VHDL)
        ext = HdlHtmlExtractor.from_directory(tmp)
        assert len(ext) == 2


def test_ignores_frameset_and_toolbarframe():
    """Top-level .htm and ToolbarFrame files must not produce source entries."""
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "test_vhd", _FRAME0_VHDL)
        # Add a fake ToolbarFrame
        with open(os.path.join(tmp, "test_vhdToolbarFrame0.htm"), "w") as f:
            f.write(_HDL_HEADER + "<body></body></html>")
        ext = HdlHtmlExtractor.from_directory(tmp)
        # Should only have the one source file
        assert ext.source_files() == ["test.vhd"]


def test_ignores_frame1_side_data():
    """ContentFrame1 'Side Data was not exported' must not produce an entry."""
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "test_vhd", _FRAME0_VHDL)
        ext = HdlHtmlExtractor.from_directory(tmp)
        # frame1 produces no entry even if it exists
        for name in ext.source_files():
            assert "ContentFrame1" not in name


def test_empty_dir_returns_empty_extractor():
    with tempfile.TemporaryDirectory() as tmp:
        ext = HdlHtmlExtractor.from_directory(tmp)
        assert len(ext) == 0
        assert not ext


def test_non_hdl_designer_file_ignored():
    """Files without the 'Generated by HDL Designer' comment are skipped."""
    with tempfile.TemporaryDirectory() as tmp:
        content = "<html><body><pre>signal x : std_logic;</pre></body></html>"
        with open(os.path.join(tmp, "fake_vhdContentFrame0.htm"), "w") as f:
            f.write(content)
        ext = HdlHtmlExtractor.from_directory(tmp)
        assert len(ext) == 0


# ── Tag stripping and entity decoding ─────────────────────────────────────────

def test_span_tags_stripped():
    """span class=K/C/T/S must vanish from extracted text."""
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "test_vhd", _FRAME0_VHDL)
        ext = HdlHtmlExtractor.from_directory(tmp)
        text = ext.text("test.vhd")
        assert "<span" not in text
        assert "class=" not in text


def test_vhdl_keywords_preserved():
    """Keywords must be intact after tag removal."""
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "test_vhd", _FRAME0_VHDL)
        ext = HdlHtmlExtractor.from_directory(tmp)
        text = ext.text("test.vhd")
        assert "package" in text
        assert "constant" in text
        assert "CLK_FREQ" in text


def test_html_entities_decoded():
    """HTML entities &amp; &lt; &gt; must be decoded in extracted text."""
    with tempfile.TemporaryDirectory() as tmp:
        _make_export(tmp, "uut_vhd", _FRAME0_ENTITIES)
        ext = HdlHtmlExtractor.from_directory(tmp)
        text = ext.text("uut.vhd")
        assert "&amp;" not in text
        assert "& entities < >" in text


